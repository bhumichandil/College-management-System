    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        String enroll = senrollnumber.getText().trim();
    String name = sname.getText().trim();
    String cls = sclass.getText().trim();

    if(enroll.isEmpty() || name.isEmpty() || cls.isEmpty()){
        JOptionPane.showMessageDialog(this,"Fill all fields");
        return;
    }

    try {
        Class.forName("com.mysql.cj.jdbc.Driver");
         Connection con = DriverManager.getConnection(
            "jdbc:mysql://localhost:3306/clgdata","root","272006");

        String query = "UPDATE clgdata SET name=?, class=? WHERE enrollnumber=?";
        PreparedStatement pstm = con.prepareStatement(query);

        pstm.setString(1, name);
        pstm.setString(2, cls);
        pstm.setInt(3, Integer.parseInt(enroll));

        int updated = pstm.executeUpdate();

        if(updated > 0){
            JOptionPane.showMessageDialog(this,"Student Updated Successfully");
        } else {
            JOptionPane.showMessageDialog(this,"No Record Found to Update");
        }

        con.close();
    } catch(Exception e){
        JOptionPane.showMessageDialog(this,e);
    }

     
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // TODO add your handling code here:
        try{
            //load driver
            Class.forName("com.mysql.cj.jdbc.Driver");
            //create connection
            Connection con = DriverManager.getConnection("jdbc:mysql://localhost:3306/clgdata","root","272006");
            //create query
            String query = "Select * from clgdata";
            PreparedStatement pstm = con.prepareStatement(query);
            //execute query
           ResultSet rs = pstm.executeQuery();
           
           DefaultTableModel model = (DefaultTableModel)table.getModel();
           
           while(rs.next()){
               int enrollnumber = rs.getInt("enrollnumber");
               String studentenrollnumber = Integer.toString(enrollnumber);
               
               String StudentName = rs.getString("Name");
               String className = rs.getString("class");
               
               String row[] = {studentenrollnumber,StudentName,className};
               model.addRow(row);
           }
           con.close();
        }
        catch(Exception e){
            JOptionPane.showMessageDialog(this,e);
        }
        
       

    }//GEN-LAST:event_jButton3ActionPerformed

