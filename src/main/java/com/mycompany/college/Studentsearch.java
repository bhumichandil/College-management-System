    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        String studentenrollnumber =enrollnumber.getText();
        DefaultTableModel model = (DefaultTableModel)table.getModel();
        if(studentenrollnumber.isEmpty()){
            JOptionPane.showMessageDialog(this,"Please enter enrollnumber");
            
        }
        try{
            model.setRowCount(0);
            //load driver 
            Class.forName("com.mysql.cj.jdbc.Driver");
            //create connection
            Connection con = DriverManager.getConnection("jdbc:mysql://localhost:3306/clgdata","root","272006");
            
            String query = "Select * from clgdata WHERE enrollnumber=?";
            PreparedStatement pstm = con.prepareStatement(query);
            pstm.setString( 1, studentenrollnumber);
            pstm.executeQuery();
            ResultSet rs = pstm.executeQuery();
            boolean hasResult = false;
            while(rs.next()){
                hasResult = true;
                int enrollnumber = rs.getInt("enrollnumber");
                String studentenrollNumber = Integer.toString(enrollnumber);
                String Studentname = rs.getString("name");
                String Studentclass = rs.getString("class");
                String row[] = {studentenrollNumber,Studentname,Studentclass};
                model.addRow(row);
                
            }
            if(!hasResult){
                JOptionPane.showMessageDialog(this,"No Result Found");
            }
                        }
        catch(Exception e){
            JOptionPane.showMessageDialog(this, e);
        }
        
        
        
        
    }//GEN-LAST:event_jButton2ActionPerformed

