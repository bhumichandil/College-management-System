    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String studentname = sname.getText();
        String studentclass = sclass.getText();
        String sEnrollnumber = senrollnumber.getText();
        int studentenrollnumber = Integer.parseInt(sEnrollnumber);
        try{
           //load driver
           Class.forName("com.mysql.cj.jdbc.Driver");
           //create connection 
           Connection con = DriverManager.getConnection("jdbc:mysql://localhost:3306/clgdata","root","272006");
           String query = "Insert INTO clgdata VALUES(?,?,?)";
           PreparedStatement pstm = con.prepareStatement(query);
           pstm.setInt(1,studentenrollnumber);
           pstm.setString(2,studentname);
           pstm.setString(3,studentclass);
           //execute query
           pstm.executeUpdate();
           JOptionPane.showMessageDialog(this,"data inserted");
           
           
           
        }catch(Exception e){
            JOptionPane.showMessageDialog(this,e);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

